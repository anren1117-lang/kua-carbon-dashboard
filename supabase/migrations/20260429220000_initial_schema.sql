-- ============================================================
-- 8. RLS — enable on every table, then permissive policies for anon.
--    Tighten these when real Supabase Auth replaces the client-side gate.
-- ============================================================
do $$
declare t text;
begin
  for t in
    select unnest(array[
      'emission_factors','audit_log',
      'scope1_heating_oil','scope1_propane','scope1_refrigerants','scope1_fleet',
      'scope2_meter_readings','scope2_utility_bills',
      'renewables_solar','renewables_geothermal','renewables_wind',
      'sinks_trees','sinks_soil_samples',
      'framework_drafts'
    ])
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "anon read"   on %I', t);
    execute format('drop policy if exists "anon write"  on %I', t);
    execute format('drop policy if exists "anon update" on %I', t);
    execute format('drop policy if exists "anon delete" on %I', t);
    execute format('create policy "anon read"   on %I for select using (true)', t);
    execute format('create policy "anon write"  on %I for insert with check (true)', t);
    execute format('create policy "anon update" on %I for update using (true) with check (true)', t);
    execute format('create policy "anon delete" on %I for delete using (true)', t);
  end loop;
end $$;

