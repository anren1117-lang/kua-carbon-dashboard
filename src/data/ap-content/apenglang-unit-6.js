      content:
`**Position** = the writer\'s stance on a contested issue.

**Why identify position?**
- Without it, you can\'t evaluate the argument.
- Helps you read for bias.
- Lets you compare across writers on same issue.

**How to find position.**

**Look for thesis.** Often stated explicitly in essays. May be implied in narrative or descriptive writing.

**Look at what\'s emphasized.** What does the writer spend most time on? Repeatedly return to?

**Look at framing.** What words used? What metaphors? What included/excluded?

**Look at who\'s quoted.** Whose voices given platform? Whose silenced or attacked?

**Look at conclusions.** Where does the argument end up?

**Look at what\'s assumed.** Sometimes position revealed by what writer takes for granted.

**Distinguish positions from facts.**
- "Unemployment was 3.7% in March" — fact.
- "Unemployment of 3.7% reflects a healthy economy" — position.
- Same data, different interpretation.

**Don\'t reduce to "for/against."**
- Most positions are more nuanced.
- "For policy X with these caveats" or "against current policy but open to alternative Y."

**Position vs argument.**
- Position = what you think.
- Argument = how you justify it.
- Different writers can hold same position with different arguments (or vice versa).

**Examples of nuanced positions.**

"I support raising the minimum wage to $15, but the increase should phase in over 3 years and exempt small businesses with under 20 employees."

"I oppose mass incarceration but recognize some violent offenders pose genuine danger; we need alternatives, not abolition."

**A writer\'s position is theirs.** Disagreeing with it doesn\'t mean it\'s wrong; understanding it is part of fair reading.`,
